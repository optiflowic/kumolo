//go:build ignore

// genvalidation generates the input shape graph for one service from the botocore model
// bundled with awscli2. The graph covers every shape reachable from the input of each
// operation the router dispatches: member names and types, and the required, length,
// pattern, enum and numeric range constraints.
//
// Usage:
//
//	go run tools/genvalidation/main.go -model <service-2.json> \
//	  -router internal/cognito/router.go -package cognito \
//	  -out internal/cognito/validation_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
)

type model struct {
	Metadata struct {
		APIVersion     string `json:"apiVersion"`
		EndpointPrefix string `json:"endpointPrefix"`
	} `json:"metadata"`
	Operations map[string]struct {
		Input *struct {
			Shape string `json:"shape"`
		} `json:"input"`
	} `json:"operations"`
	Shapes map[string]shape `json:"shapes"`
}

type shape struct {
	Type      string            `json:"type"`
	Required  []string          `json:"required"`
	Members   map[string]member `json:"members"`
	Member    *member           `json:"member"`
	Key       *member           `json:"key"`
	Value     *member           `json:"value"`
	Enum      []string          `json:"enum"`
	Min       *float64          `json:"min"`
	Max       *float64          `json:"max"`
	Pattern   string            `json:"pattern"`
	Sensitive bool              `json:"sensitive"`
}

type member struct {
	Shape string `json:"shape"`
}

func main() {
	modelPath := flag.String("model", "", "path to botocore service-2.json")
	routerPath := flag.String("router", "", "router.go with case \"<Operation>\": dispatch")
	pkg := flag.String("package", "", "package name of the generated file")
	outPath := flag.String("out", "", "output Go file path")
	flag.Parse()
	if *modelPath == "" || *routerPath == "" || *pkg == "" || *outPath == "" {
		flag.Usage()
		os.Exit(2)
	}

	if err := run(*modelPath, *routerPath, *pkg, *outPath); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(modelPath, routerPath, pkg, outPath string) error {
	raw, err := os.ReadFile(modelPath)
	if err != nil {
		return err
	}
	var m model
	if err := json.Unmarshal(raw, &m); err != nil {
		return fmt.Errorf("parse model: %w", err)
	}
	ops, err := implementedOps(routerPath)
	if err != nil {
		return err
	}

	used := map[string]bool{}
	var inputs bytes.Buffer
	for _, op := range ops {
		o, ok := m.Operations[op]
		if !ok || o.Input == nil {
			return fmt.Errorf("%s: no input shape in model", op)
		}
		if err := markUsed(m.Shapes, o.Input.Shape, used); err != nil {
			return fmt.Errorf("%s: %w", op, err)
		}
		fmt.Fprintf(&inputs, "%q: shape%s,\n", op, o.Input.Shape)
	}

	shapeNames := make([]string, 0, len(used))
	for name := range used {
		shapeNames = append(shapeNames, name)
	}
	sort.Strings(shapeNames)

	var out bytes.Buffer
	fmt.Fprintf(
		&out,
		"// Code generated by tools/genvalidation from the botocore %s model (%s); DO NOT EDIT.\n\n",
		m.Metadata.EndpointPrefix,
		m.Metadata.APIVersion,
	)
	fmt.Fprintf(&out, "package %s\n\nvar (\n", pkg)
	for _, name := range shapeNames {
		lit, err := shapeLiteral(m.Shapes[name])
		if err != nil {
			return fmt.Errorf("shape %s: %w", name, err)
		}
		fmt.Fprintf(&out, "shape%s = &inputShape{%s}\n", name, lit)
	}
	out.WriteString(")\n\n")
	out.WriteString("// inputRules maps each operation to its input structure.\n")
	out.WriteString("var inputRules = map[string]*inputShape{\n")
	out.Write(inputs.Bytes())
	out.WriteString("}\n")

	src, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("format output: %w", err)
	}
	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		return err
	}
	fmt.Printf("%d operations, %d shapes\n", len(ops), len(shapeNames))
	return nil
}

func implementedOps(routerPath string) ([]string, error) {
	src, err := os.ReadFile(routerPath)
	if err != nil {
		return nil, err
	}
	var ops []string
	for _, m := range regexp.MustCompile(`case "(\w+)":`).FindAllStringSubmatch(string(src), -1) {
		ops = append(ops, m[1])
	}
	sort.Strings(ops)
	return ops, nil
}

func markUsed(shapes map[string]shape, name string, used map[string]bool) error {
	if used[name] {
		return nil
	}
	s, ok := shapes[name]
	if !ok {
		return fmt.Errorf("shape %s not found in model", name)
	}
	used[name] = true
	refs := make([]*member, 0, len(s.Members)+3)
	for _, m := range s.Members {
		refs = append(refs, &m)
	}
	refs = append(refs, s.Member, s.Key, s.Value)
	for _, m := range refs {
		if m == nil {
			continue
		}
		if err := markUsed(shapes, m.Shape, used); err != nil {
			return err
		}
	}
	return nil
}

func shapeLiteral(s shape) (string, error) {
	var b bytes.Buffer
	switch s.Type {
	case "structure":
		b.WriteString("kind: kindStructure, members: []memberRule{")
		required := map[string]bool{}
		for _, name := range s.Required {
			required[name] = true
		}
		names := make([]string, 0, len(s.Members))
		for name := range s.Members {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			fmt.Fprintf(&b, "{name: %q, ", name)
			if required[name] {
				b.WriteString("required: true, ")
			}
			fmt.Fprintf(&b, "shape: shape%s},", s.Members[name].Shape)
		}
		b.WriteString("}")
	case "list":
		fmt.Fprintf(&b, "kind: kindList, member: shape%s", s.Member.Shape)
	case "map":
		fmt.Fprintf(&b, "kind: kindMap, key: shape%s, value: shape%s", s.Key.Shape, s.Value.Shape)
	case "string":
		b.WriteString("kind: kindString")
	case "integer":
		b.WriteString("kind: kindInteger")
	case "boolean":
		b.WriteString("kind: kindBoolean")
	default:
		return "", fmt.Errorf("unsupported shape type %q", s.Type)
	}
	if s.Sensitive {
		b.WriteString(", sensitive: true")
	}
	if s.Min != nil {
		fmt.Fprintf(&b, ", min: new(int64(%d))", int64(*s.Min))
	}
	if s.Max != nil {
		fmt.Fprintf(&b, ", max: new(int64(%d))", int64(*s.Max))
	}
	if s.Pattern != "" {
		// The table must fail to generate rather than panic at kumolo startup.
		if _, err := regexp.Compile(`^(?:` + s.Pattern + `)$`); err != nil {
			return "", fmt.Errorf("pattern %q: %w", s.Pattern, err)
		}
		fmt.Fprintf(&b, ", pattern: mustPattern(%s)", strconv.Quote(s.Pattern))
	}
	if len(s.Enum) > 0 {
		b.WriteString(", enum: []string{")
		for i, v := range s.Enum {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.Quote(v))
		}
		b.WriteString("}")
	}
	return b.String(), nil
}
